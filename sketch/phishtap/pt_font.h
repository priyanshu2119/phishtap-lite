#define PT_FONT_COUNT (sizeof(PT_FONT) / sizeof(PT_FONT[0]))

/*
 * Look up a glyph. Lowercase is folded to uppercase because the font has no
 * descenders and a 5x7 cell cannot distinguish them legibly at this size.
 * Returns NULL for anything unmapped; callers render NULL as a blank cell
 * rather than failing, so an unexpected character degrades gracefully.
 */
inline const uint8_t* ptGlyphFor(char c) {
  if (c >= 'a' && c <= 'z') c = (char)(c - 'a' + 'A');
  for (unsigned int i = 0; i < PT_FONT_COUNT; ++i) {
    if (PT_FONT[i].ch == c) return PT_FONT[i].rows;
  }
  return NULL;
}

